export function updateDocumentDirection(lang: Language = "fa") {
  const root = document.documentElement;
  const isFa = lang === "fa";
  root.setAttribute("lang", isFa ? "fa" : "en");
  root.setAttribute("dir", isFa ? "rtl" : "ltr");
}
